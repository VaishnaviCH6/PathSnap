"""Evaluation-only observation accuracy for PathSnap's *student-test* partition.

This function runs AFTER the model and HMM have produced a Prediction.  It
reads labels generated by M2's supervised student-test evaluation pipeline,
never passes those labels into the predictor, and is not intended for private
or reserved evaluator-test trips.

Enable explicitly with:
  PATHSNAP_MODE=integrated
  PATHSNAP_PARTITION=student_test
  PATHSNAP_EVALUATOR=backend.student_test_evaluator:evaluate_observation_top1
  PATHSNAP_STUDENT_TEST_LABEL_DIR=<repo>/outputs/labelled/student_test
"""
from __future__ import annotations

import os
import re
from pathlib import Path
from typing import TYPE_CHECKING

import pandas as pd

if TYPE_CHECKING:
    from backend.pipeline import Prediction


def evaluate_observation_top1(trip_id: str, prediction: "Prediction") -> float:
    """Top-1 candidate-arc accuracy on supervised-eligible student-test points.

    The denominator follows the team's M2 evaluation script: only GPS
    observations with a positive reference candidate AND a predicted arc are
    comparable. Unlabeled/ambiguous observations are not counted as errors.
    Returns a proportion in [0, 1], not a percent.
    """
    if os.getenv("PATHSNAP_MODE") != "integrated" or os.getenv("PATHSNAP_PARTITION") != "student_test":
        raise RuntimeError("Student-test labels may be read only in integrated student_test evaluation")
    if re.fullmatch(r"[0-9]{8}", trip_id) is None:
        raise ValueError("Invalid student-test trip ID")

    label_dir_value = os.getenv("PATHSNAP_STUDENT_TEST_LABEL_DIR")
    if not label_dir_value:
        raise RuntimeError("PATHSNAP_STUDENT_TEST_LABEL_DIR is required for student-test evaluation")
    label_dir = Path(label_dir_value).resolve()
    if label_dir.name != "student_test":
        raise RuntimeError("Student-test label directory must be named student_test")
    label_file = label_dir / f"{trip_id}_labelled_candidates.csv"
    if not label_file.is_file():
        raise FileNotFoundError(f"Student-test evaluation labels unavailable: {label_file}")

    labels = pd.read_csv(label_file, usecols=["observation_id", "candidate_arc_id", "label"])
    positive = labels.loc[labels["label"] == 1, ["observation_id", "candidate_arc_id"]]
    if positive["observation_id"].duplicated().any():
        raise ValueError(f"Multiple positive reference candidates for trip {trip_id}")
    positive_map = dict(zip(positive["observation_id"].astype(int),
                            positive["candidate_arc_id"].astype(int)))

    correct = comparable = 0
    for observation_id, arc_id in enumerate(prediction.observation_arc_ids):
        if arc_id is None or observation_id not in positive_map:
            continue
        comparable += 1
        correct += (int(arc_id) == positive_map[observation_id])
    if not comparable:
        raise ValueError(f"No comparable supervised student-test observations in trip {trip_id}")
    return correct / comparable
